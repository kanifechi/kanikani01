"""東証の値幅制限（ストップ高・ストップ安）の通常の制限値幅表。

基準値段（ふつうは前日の終値）に応じて、1日に動ける幅が決まる。
制限値幅の拡大（連続ストップ時など）や、上場初日の特別な扱いはここでは扱わない。
"""

from __future__ import annotations

# (基準値段の上限（未満）, 制限値幅)
_LIMIT_TABLE = [
    (100, 30), (200, 50), (500, 80), (700, 100), (1_000, 150),
    (1_500, 300), (2_000, 400), (3_000, 500), (5_000, 700), (7_000, 1_000),
    (10_000, 1_500), (15_000, 3_000), (20_000, 4_000), (30_000, 5_000),
    (50_000, 7_000), (70_000, 10_000), (100_000, 15_000), (150_000, 30_000),
    (200_000, 40_000), (300_000, 50_000), (500_000, 70_000), (700_000, 100_000),
    (1_000_000, 150_000), (1_500_000, 300_000), (2_000_000, 400_000),
    (3_000_000, 500_000), (5_000_000, 700_000), (7_000_000, 1_000_000),
    (10_000_000, 1_500_000), (15_000_000, 3_000_000), (20_000_000, 4_000_000),
    (30_000_000, 5_000_000), (50_000_000, 7_000_000),
]
_LIMIT_OVER = 10_000_000


def price_limit(base_price: float) -> float:
    """基準値段に対する制限値幅（円）。"""
    if base_price <= 0:
        raise ValueError(f"基準値段が正ではありません: {base_price}")
    for upper, width in _LIMIT_TABLE:
        if base_price < upper:
            return float(width)
    return float(_LIMIT_OVER)
